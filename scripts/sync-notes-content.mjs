import { readFile, readdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const sourceDir =
	process.env.PORTFOLIO_NOTES_SOURCE ??
	join(
		homedir(),
		'Library/Mobile Documents/iCloud~md~obsidian/Documents/hanif-md/projects/portfolio-knowledge-library'
	);
const outputFile = fileURLToPath(new URL('../src/data/notes.generated.ts', import.meta.url));
const section = (markdown, heading) => {
	const marker = `## ${heading}\n`;
	const start = markdown.indexOf(marker);
	if (start === -1) throw new Error(`Missing "## ${heading}" section`);
	const remainder = markdown.slice(start + marker.length);
	const end = remainder.search(/^## /m);
	return remainder.slice(0, end === -1 ? undefined : end).trim();
};

const oneLine = (text) => text.replace(/\s*\n\s*/g, ' ').trim();
const slugify = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

function parse(markdown, filename) {
	const title = markdown.match(/^# (.+)$/m)?.[1]?.trim();
	if (!title) throw new Error(`${filename}: missing title`);

	const listedEntries = section(markdown, 'Entries')
		.split('\n')
		.map((line) => line.match(/^\d+\.\s+(.+?)\.?$/)?.[1])
		.filter(Boolean);
	const draft = section(markdown, 'Draft');
	const matches = [...draft.matchAll(/^### (.+)$/gm)];
	const entries = matches.map((match, index) => ({
		title: match[1].trim(),
		body: draft
			.slice(match.index + match[0].length, matches[index + 1]?.index ?? draft.length)
			.trim()
			.split(/\n\s*\n/)
			.map(oneLine)
	}));

	if (!entries.length) throw new Error(`${filename}: no draft entries`);
	if (listedEntries.join('\n') !== entries.map(({ title }) => title).join('\n')) {
		throw new Error(`${filename}: Entries list and Draft headings do not match`);
	}

	return {
		slug: slugify(title),
		title,
		purpose: oneLine(section(markdown, 'Purpose')),
		entries
	};
}

const files = (await readdir(sourceDir)).filter((name) => /^\d+ .+\.md$/.test(name)).sort();
if (!files.length) throw new Error(`No numbered Markdown files found in ${sourceDir}`);

const sections = await Promise.all(
	files.map(async (filename) => parse(await readFile(join(sourceDir, filename), 'utf8'), filename))
);
const generated = `// Generated by bun run notes:sync. Do not edit directly.\n\nexport default ${JSON.stringify(sections, null, '\t')} as const;\n`;

if (process.argv.includes('--check')) {
	const current = await readFile(outputFile, 'utf8').catch(() => '');
	if (current !== generated) {
		console.error('Notes content is out of date. Run: bun run notes:sync');
		process.exitCode = 1;
	}
} else {
	await writeFile(outputFile, generated);
	console.log(`Synced ${sections.length} sections and ${sections.reduce((sum, item) => sum + item.entries.length, 0)} entries.`);
}
